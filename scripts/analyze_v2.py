    # rank stability (E12)
    ha_s, t_s = topk_from(R["atp_selection"]); ha_t, t_t = topk_from(R["atp_test"])
    rho = spearmanr(ha_s.ravel(), ha_t.ravel()).correlation
    n_ = len(R["atp_selection"]); h1, h2 = list(range(0, n_, 2)), list(range(1, n_, 2))
    ha_a, t_a = topk_from(R["atp_selection"], idx=h1); ha_b, t_b = topk_from(R["atp_selection"], idx=h2)
    rho_half = spearmanr(ha_a.ravel(), ha_b.ravel()).correlation
    out.append(f"\nRank stability: selection vs test Spearman (all heads) {rho:.3f}, top-10 Jaccard {jacc(t_s, t_t):.2f}; "
               f"split-half inside selection: Spearman {rho_half:.3f}, Jaccard {jacc(t_a, t_b):.2f}")
