# ============================ behaviour ============================
BEH = {}
for m in MODELS:
    f = os.path.join(RD, f"behaviour_{m}.jsonl")
    if os.path.exists(f): BEH[m] = [json.loads(l) for l in open(f)]
curves = {}
for m, rows in BEH.items():
    src = f"results/A/behaviour_{m}.jsonl (job {JOBS.get('behaviour_' + m, '?')})"
    for fmt in ["F1", "F2", "F3"]:
        for split in (["test", "all"] if fmt == "F1" else ["test"]):
            R_ = [r for r in rows if r["fmt"] == fmt and (split == "all" or r["split"] == split)]
            if not R_: continue
            by = collections.defaultdict(lambda: collections.defaultdict(list))
            for r in R_: by[r["ck"]][r["pair_id"]].append(r["p_low"])
            if "C1k1" not in by: continue
            pairs = sorted(by["C1k1"])
            M = {ck: np.array([np.mean(by[ck][p]) for p in pairs]) for ck in CKS if ck in by and len(by[ck]) == len(pairs)}
            mass = np.mean([r["mass"] for r in R_])
            out.append(f"\n## {SHORT[m]} · {fmt} · split={split} (n pairs={len(pairs)}, 8 variants each; mean A+B mass {mass:.3f})\n")
            out.append("| cond | P_low [95% CI] | shift vs C1 [95% CI] | shift vs C0 | flip (% pairs P_low>.5) | P_low HF / LF | tokens |\n|---|---|---|---|---|---|---|")
            base = f"{SHORT[m]}.{fmt}.{split}"
            put(f"{base}.mass", mass, n=len(R_), src=src)
            cur = {}
            for ck in CKS:
                if ck not in M: continue
                x = M[ck]; d = x - M["C1k1"]; ci = boot_mean(x); dci = boot_mean(d)
                d0 = (x - M["C0k1"]).mean() * 100 if "C0k1" in M else float("nan")
                hf = np.mean([r["p_low"] for r in R_ if r["ck"] == ck and r["order"] == "HF"])
                lf = np.mean([r["p_low"] for r in R_ if r["ck"] == ck and r["order"] == "LF"])
                nt = np.mean([r["ntok"] for r in R_ if r["ck"] == ck])
                out.append(f"| {ck} | {x.mean():.3f} [{ci[0]:.3f}, {ci[1]:.3f}] | {d.mean()*100:+.1f} [{dci[0]*100:+.1f}, {dci[1]*100:+.1f}] | {d0:+.1f} | {(x > .5).mean()*100:.0f}% | {hf:.3f} / {lf:.3f} | {nt:.0f} |")
                put(f"{base}.{ck}.p_low", x.mean(), ci, len(pairs), src)
                put(f"{base}.{ck}.shift_vs_C1_pts", d.mean() * 100, dci * 100, len(pairs), src)
                put(f"{base}.{ck}.flip_pct", (x > .5).mean() * 100, None, len(pairs), src)
                cur[ck] = (x.mean(), ci)
            curves[(m, fmt, split)] = cur
            # named contrasts (paired over pairs)
            for a, b in [("C3k4", "C2k4"), ("C7k4", "C2k4"), ("C7k4", "C3k4"), ("C7k2", "C2k2"), ("C3k2", "C2k2")]:
                if a in M and b in M:
                    d = (M[a] - M[b]) * 100; ci = boot_mean(d)
                    out.append(f"\n{a} − {b}: {d.mean():+.1f} pts [{ci[0]:+.1f}, {ci[1]:+.1f}]")
                    put(f"{base}.{a}_minus_{b}_pts", d.mean(), ci, len(pairs), src)
            if "C5k4" in M and "C2k4" in M:  # length control: C5 shift as % of C2k4 shift (ratio of means, bootstrap)
                s5 = M["C5k4"] - M["C1k1"]; s2 = M["C2k4"] - M["C1k1"]
                idx = rng.integers(0, len(s5), (2000, len(s5)))
                rat = s5[idx].mean(1) / s2[idx].mean(1) * 100
                v = s5.mean() / s2.mean() * 100; ci = np.percentile(rat, [2.5, 97.5])
                out.append(f"\nC5 shift as % of C2k4 shift: {v:.0f}% [{ci[0]:.0f}, {ci[1]:.0f}]")
                put(f"{base}.C5_pct_of_C2k4_shift", v, ci, len(pairs), src)
            out.append("")

