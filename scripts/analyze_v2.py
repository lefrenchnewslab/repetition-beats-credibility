def recovery(V, name, idx=None):
    V = V if idx is None else [V[i] for i in idx]
    lc = np.mean([v["ld_clean"] for v in V]); lk = np.mean([v["ld_corrupt"] for v in V]); pv = np.mean([v[name] for v in V])
    return (lk - pv) / (lk - lc) * 100
def rec_ci(V, name, B=2000):  # cluster bootstrap over pairs (E14)
    by = collections.defaultdict(list)
    for i, v in enumerate(V): by[v["pair_id"]].append(i)
    P_ = list(by)
    bs = []
    for _ in range(B):
        pick = rng.integers(0, len(P_), len(P_)); idx = [i for p in pick for i in by[P_[p]]]
        bs.append(recovery(V, name, idx))
    return np.percentile(bs, [2.5, 97.5])
def topk_from(per, k=10, idx=None):
    per = per if idx is None else [per[i] for i in idx]
    ha = np.mean([p["head_attr"] for p in per], 0); return ha, set(map(tuple, np.dstack(np.unravel_index(np.argsort(ha.ravel())[:k], ha.shape))[0].tolist()))
def jacc(a, b): return len(a & b) / len(a | b)
for (m, fmt), R in sorted(PAT.items()):
    pf = fmt.replace("-", "_")
    src = f"results/A/patch_{pf}_{m}.json (job {JOBS.get(f'patch_{pf}_' + m, '?')})"
    V = R["verify"]; b = f"{SHORT[m]}.{fmt}.patch"
    lc = np.array([v["ld_clean"] for v in V]); lk = np.array([v["ld_corrupt"] for v in V])
    out.append(f"\n## Patching {SHORT[m]} · {fmt} (rank: AtP on {R['n_atp_selection']} SELECTION items; verify: {len(V)} TEST items from "
               f"{len(set(v['pair_id'] for v in V))} pairs; eligible sel/test {R['eligible']}; skipped {R['verify_skipped']})\n")
    out.append(f"mean LD clean {lc.mean():.2f}, corrupt {lk.mean():.2f}; mean shared-suffix length {np.mean([v['S'] for v in V]):.0f} tokens\n")
    out.append("| head set | recovery % [95% CI, cluster bootstrap over pairs] |\n|---|---|")
    for name in ["top1", "top5", "top10", "top20", "mean_top1", "mean_top5", "mean_top10", "mean_top20", "sun_decision_head"]:
        if name not in R["hsets"]: continue
        v = recovery(V, name); ci = rec_ci(V, name)
        out.append(f"| {name} {R['hsets'][name] if name.endswith(('top1', 'head')) else ''} | {v:.1f} [{ci[0]:.1f}, {ci[1]:.1f}] |")
        put(f"{b}.{name}.recovery_pct", v, ci, len(V), src)
    rnd = [recovery(V, n) for n in R["hsets"] if n.startswith("rand10_")]
    mrnd = [recovery(V, n) for n in R["hsets"] if n.startswith("mean_rand10_")]
    out.append(f"| 10 random heads, patch (×{len(rnd)}) | mean {np.mean(rnd):.1f}, 95th pct {np.percentile(rnd, 95):.1f}, max {np.max(rnd):.1f} |")
    out.append(f"| 10 random heads, mean-ablate (×{len(mrnd)}) | mean {np.mean(mrnd):.1f}, max {np.max(mrnd):.1f} |")
    put(f"{b}.rand10.recovery_mean", np.mean(rnd), n=len(rnd), src=src); put(f"{b}.rand10.recovery_max", np.max(rnd), n=len(rnd), src=src)
    put(f"{b}.rand10.recovery_p95", np.percentile(rnd, 95), n=len(rnd), src=src)
    singles = [(n, recovery(V, n)) for n in R["hsets"] if n.startswith("single_")]
    out.append("\nSingle-head recovery (top-10 by selection AtP): " + ", ".join(f"L{n.split('_')[1]}H{n.split('_')[2]} {v:.1f}%" for n, v in singles))
    if fmt == "F1": H1[m] = (recovery(V, "top10"), float(np.percentile(rnd, 95)), len(rnd))  # amendment 4: both conditions
