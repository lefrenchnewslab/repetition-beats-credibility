rng = np.random.default_rng(0)
JOBS = json.load(open(os.path.join(RD, "jobs.json"))) if os.path.exists(os.path.join(RD, "jobs.json")) else {}
NUM = {}
def put(key, value, ci=None, n=None, src=None):
    NUM[key] = {"value": None if value is None else float(value), "ci": None if ci is None else [float(ci[0]), float(ci[1])],
                "n": None if n is None else int(n), "source": src}
def boot_mean(x, B=2000):
    x = np.asarray(x); bs = x[rng.integers(0, len(x), (B, len(x)))].mean(1); return np.percentile(bs, [2.5, 97.5])
MODELS = ["Llama-3.1-8B-Instruct", "Qwen2.5-7B-Instruct", "gemma-3-12b-it", "Qwen2.5-32B-Instruct"]
SHORT = {"Llama-3.1-8B-Instruct": "Llama-8B", "Qwen2.5-7B-Instruct": "Qwen-7B", "gemma-3-12b-it": "Gemma-12B", "Qwen2.5-32B-Instruct": "Qwen-32B"}
CKS = ["C0k1", "C0rk4", "C1k1", "C2k2", "C2k4", "C2k8", "C3k2", "C3k4", "C4k2", "C4k4", "C5k4", "C6k2", "C6k4", "C7k2", "C7k4"]
