"""SPRINT Block F (14-15 Nov 2026) - analysis of the reviewer controls. New file.
  python3 scripts/analyze_f.py   -> results/F/summary_F.md, numbers_F.json
"""
import json, os, glob, collections
import numpy as np
S = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); RF = f"{S}/results/F"; RA = f"{S}/results/A"
rng = np.random.default_rng(0); NUM = {}; out = ["# Block F summary (auto-generated by analyze_f.py)\n"]
def put(k, v, ci=None, n=None, src=None): NUM[k] = {"value": None if v is None else float(v), "ci": None if ci is None else [float(c) for c in ci], "n": n, "source": src}
SH = {"Llama-3.1-8B-Instruct": "Llama-8B", "Qwen2.5-7B-Instruct": "Qwen-7B", "gemma-3-12b-it": "Gemma-12B", "Qwen2.5-32B-Instruct": "Qwen-32B"}
def pairmeans(files, fmt):
    D = collections.defaultdict(lambda: collections.defaultdict(list)); T = collections.defaultdict(list)
    for f in files:
        if not os.path.exists(f): continue
        for l in open(f):
            x = json.loads(l)
            if x.get("split", "test") == "test" and x["fmt"] == fmt: D[x["ck"]][x["pair_id"]].append(x["p_low"]); T[x["ck"]].append(x.get("ntok", 0))
    return {ck: {p: np.mean(v) for p, v in d.items()} for ck, d in D.items()}, {ck: np.mean(v) for ck, v in T.items()}
def boot(fn, P, B=2000):
    P = np.array(P); return np.percentile([fn(P[rng.integers(0, len(P), len(P))]) for _ in range(B)], [2.5, 97.5])
# ---------------- F1 ----------------
out.append("## F1 - repetition or wording?\n")
for fmt, sub in (("F3", ""), ("F1", "/f1")):
    for tag, short in SH.items():
        fF = f"{RF}{sub}/behaviour_{tag}.jsonl"
        if not os.path.exists(fF): continue
        M, T = pairmeans([f"{RA}/behaviour_{tag}.jsonl", fF], fmt)
        need = ["C1k1", "C2k4", "C3k4", "C7k4", "C7k1t1", "C7k1t2", "C7k1t3", "C8k4", "C5pk4"]
        if any(c not in M for c in need): out.append(f"- {short} {fmt}: missing {[c for c in need if c not in M]}"); continue
        P = sorted(set.intersection(*[set(M[c]) for c in need])); g = lambda ck, ps: np.array([M[ck][p] for p in ps])
        c7k1_all = lambda ps: (g("C1k1", ps) + g("C7k1t1", ps) + g("C7k1t2", ps) + g("C7k1t3", ps)) / 4   # template 0 == C1 (FM H1)
        c7k1_123 = lambda ps: (g("C7k1t1", ps) + g("C7k1t2", ps) + g("C7k1t3", ps)) / 3
        Q = {"W": lambda ps: (c7k1_all(ps) - g("C1k1", ps)).mean(), "W_t123": lambda ps: (c7k1_123(ps) - g("C1k1", ps)).mean(),
             "R_p": lambda ps: (g("C7k4", ps) - c7k1_all(ps)).mean(), "R_e": lambda ps: (g("C2k4", ps) - g("C1k1", ps)).mean(),
             "D": lambda ps: ((g("C7k4", ps) - c7k1_all(ps)) - (g("C2k4", ps) - g("C1k1", ps))).mean(),
             "D_t123": lambda ps: ((g("C7k4", ps) - c7k1_123(ps)) - (g("C2k4", ps) - g("C1k1", ps))).mean(),
             "L_p": lambda ps: (g("C5pk4", ps) - g("C1k1", ps)).mean(),
             "R_p_minus_L_p": lambda ps: ((g("C7k4", ps) - c7k1_all(ps)) - (g("C5pk4", ps) - g("C1k1", ps))).mean(),
             "I_2x2": lambda ps: ((g("C8k4", ps) - g("C7k4", ps)) - (g("C3k4", ps) - g("C2k4", ps))).mean(),
             "wording_main_2x2": lambda ps: (((g("C7k4", ps) + g("C8k4", ps)) - (g("C2k4", ps) + g("C3k4", ps))) / 2).mean(),
             "source_main_2x2": lambda ps: (((g("C3k4", ps) + g("C8k4", ps)) - (g("C2k4", ps) + g("C7k4", ps))) / 2).mean()}
        V = {k: (f(P) * 100, boot(f, P) * 100) for k, f in Q.items()}
        conf = (short in ("Qwen-32B", "Qwen-7B")) and fmt == "F3"
        sup = V["D"][1][0] > 0 and V["R_p"][0] > V["L_p"][0]
        out.append(f"### {short}, {fmt} ({'confirmatory' if conf else 'exploratory'}; {len(P)} pairs)\n")
        out.append("| cell | P_low |\n|---|---|\n" + "\n".join(f"| {ck} | {g(ck, P).mean():.3f} (tokens {T.get(ck, 0):.0f}) |" for ck in need))
        out.append("\n| quantity (points) | value [95% CI] |\n|---|---|\n" + "\n".join(f"| {k} | {v:+.1f} [{c[0]:+.1f}, {c[1]:+.1f}] |" for k, (v, c) in V.items()))
        tok_ratio = T["C5pk4"] / T["C7k4"] if T.get("C7k4") else None
        out.append(f"\nC5p/C7k4 token ratio {tok_ratio:.3f}{' (FLAG: > 10% shorter)' if tok_ratio and tok_ratio < .9 else ''}. "
                   f"**F1-main: {'SUPPORTED' if sup else 'NOT SUPPORTED'}** (D CI lower {V['D'][1][0]:+.1f} {'> 0' if V['D'][1][0] > 0 else '<= 0'}; R_p {V['R_p'][0]:+.1f} vs L_p {V['L_p'][0]:+.1f})\n")
        b = f"F1.{short}.{fmt}"
        for k, (v, c) in V.items(): put(f"{b}.{k}_pts", v, c, len(P), f"results/F{sub}/behaviour_{tag}.jsonl + results/A/behaviour_{tag}.jsonl")
        for ck in need: put(f"{b}.{ck}.p_low", g(ck, P).mean(), n=len(P))
        put(f"{b}.C5p_over_C7k4_tokens", tok_ratio); put(f"{b}.supported", float(sup))
# ---------------- F2 ----------------
out.append("\n## F2 - specific heads or generic bottleneck?\n")
def rec(items, name, idx=None):
    it = items if idx is None else [items[i] for i in idx]
    lk = np.mean([x["ld_corrupt"] for x in it]); lc = np.mean([x["ld_clean"] for x in it]); return (lk - np.mean([x[name] for x in it])) / (lk - lc) * 100
for tag, short in SH.items():
    f = f"{RF}/f2_patch_{tag}.json"
    if not os.path.exists(f): continue
    R = json.load(open(f)); rows = {}
    out.append(f"### {short}\n\n| contrast | n eligible / used | mean gap (logit) | flip rate | suffix | top-10 recovery [CI] | random p95 / max |\n|---|---|---|---|---|---|---|")
    for cname, C in R["contrasts"].items():
        it = C["items"]; by = collections.defaultdict(list)
        for i, x in enumerate(it): by[x["pair_id"]].append(i)
        Pp = list(by); bs = [rec(it, "top10", [i for p in rng.integers(0, len(Pp), len(Pp)) for i in by[Pp[p]]]) for _ in range(2000)]
        r10 = rec(it, "top10"); ci = np.percentile(bs, [2.5, 97.5]); rnd = [rec(it, k) for k in R["sets"] if k.startswith("rand10_")]
        gap = np.mean([x["ld_corrupt"] - x["ld_clean"] for x in it]); flip = np.mean([np.sign(x["ld_corrupt"]) != np.sign(x["ld_clean"]) for x in it])
        rows[cname] = (r10, np.percentile(rnd, 95))
        out.append(f"| {cname} | {C['n_eligible']} / {len(it)} | {gap:+.2f} | {flip*100:.0f}% | {np.mean([x['S'] for x in it]):.0f} | {r10:.1f} [{ci[0]:.1f}, {ci[1]:.1f}] | {np.percentile(rnd, 95):.1f} / {np.max(rnd):.1f} |")
        b = f"F2.{short}.{cname}"; put(f"{b}.recovery_top10_pct", r10, ci, len(it), f"results/F/f2_patch_{tag}.json"); put(f"{b}.random_p95_pct", np.percentile(rnd, 95), n=20)
        put(f"{b}.mean_gap", gap, n=len(it)); put(f"{b}.flip_rate", flip, n=len(it)); put(f"{b}.n_eligible", C["n_eligible"])
    ref = rows["C1k1->C2k4"][0]; others = [v[0] for k, v in rows.items() if k != "C1k1->C2k4"]
    specific = ref - max(others) > 20
    shared = all(rows[c][0] >= 40 and rows[c][0] > rows[c][1] for c in ("C0k1->C1k1", "C0k1->C0rk4"))
    generic = all(v[0] >= 40 for v in rows.values()) and (max(v[0] for v in rows.values()) - min(v[0] for v in rows.values())) <= 20
    out.append(f"\n- specific to the credibility-repetition conflict: **{specific}** (C1->C2 {ref:.1f} vs max other {max(others):.1f})\n- shared credibility+repetition pathway: **{shared}**\n- generic answer bottleneck: **{generic}**\n")
    put(f"F2.{short}.specific", float(specific)); put(f"F2.{short}.shared", float(shared)); put(f"F2.{short}.generic", float(generic))
# ---------------- F3 ----------------
out.append("\n## F3 - one readout, one layer\n")
for tag, short in list(SH.items())[:3]:
    f = f"{RA}/probe_c1chosen_{tag}.json"
    if not os.path.exists(f): continue
    Q = json.load(open(f))
    for L, d in Q["layers"].items():
        lab = "L*" if int(L) == Q["Lstar"] else "final"
        out.append(f"- {short} L{L} ({lab}): " + "; ".join(f"{k}: gov-label AUC {v['auc_gov_label']:.3f}, chosen-answer AUC {v['auc_chosen_answer']:.3f} (n={v['n']}, chosen=gov {v['share_chosen_equals_gov']*100:.0f}%)" for k, v in d.items()))
        for k, v in d.items(): put(f"F3.{short}.{lab}.{k}.auc_gov", v["auc_gov_label"], n=v["n"]); put(f"F3.{short}.{lab}.{k}.auc_chosen", v["auc_chosen_answer"], n=v["n"])
B2 = json.load(open(f"{S}/results/B/b2_steer_Qwen2.5-7B-Instruct.json"))
for L, o in B2["layers"].items():
    c = o["controls_100pairs"]; out.append(f"- B2 positive control (Qwen-7B, C1 residual swap at the final position, L{L}): delta P_low {c['delta_positive_control']:+.3f} (direction {c['delta_direction']:+.4f})")
    put(f"F3.B2.L{L}.positive_control_delta", c["delta_positive_control"], src="results/B/b2_steer_Qwen2.5-7B-Instruct.json")
open(f"{RF}/summary_F.md", "w").write("\n".join(out)); json.dump(NUM, open(f"{S}/numbers_F.json", "w"), indent=1); print("\n".join(out))
