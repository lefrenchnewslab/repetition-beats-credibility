"""SPRINT Block B analysis (14 Nov 2026). New file.
  python3 analyze_b.py RESULTS_B_DIR RESULTS_A_DIR -> RESULTS_B_DIR/summary_B.md, ../numbers_B.json, ../figs/figB*.png|pdf
Base P_low per prompt = Block A behaviour (same test prompts, same model, no hooks).
Metrics on pair means (8 variants); 95% CI = bootstrap over pairs (2,000). Capability: paired bootstrap over items.
"""
import json, os, sys, glob, collections
import numpy as np
RB, RA = os.path.abspath(sys.argv[1]), os.path.abspath(sys.argv[2])
SPRINT = os.path.abspath(os.path.join(RB, "..", "..")); FIG = os.path.join(SPRINT, "figs"); os.makedirs(FIG, exist_ok=True)
rng = np.random.default_rng(0); NUM = {}; out = ["# Block B summary (auto-generated by analyze_b.py)\n"]
def put(k, v, ci=None, n=None, src=None): NUM[k] = {"value": None if v is None else float(v), "ci": None if ci is None else [float(c) for c in ci], "n": n, "source": src}
TAG = sys.argv[3] if len(sys.argv) > 3 else "Qwen2.5-7B-Instruct"   # replications: pass the model tag; outputs stay in RB
base = collections.defaultdict(lambda: collections.defaultdict(list))
for l in open(f"{RA}/behaviour_{TAG}.jsonl"):
    x = json.loads(l)
    if x["split"] == "test": base[(x["fmt"], x["ck"])][x["pair_id"]].append(x["p_low"])
def pm(d): return {p: np.mean(v) for p, v in d.items()}
B = {k: pm(v) for k, v in base.items()}
SEL = json.load(open(f"{RB}/b3_select_{TAG}.json"))
def ratio_ci(num_f, den_f, pairs, B_=2000):
    pairs = np.array(pairs); vals = []
    for _ in range(B_):
        s = pairs[rng.integers(0, len(pairs), len(pairs))]; d = den_f(s)
        if d != 0: vals.append(num_f(s) / d)
    return np.percentile(vals, [2.5, 97.5])
RES = {}
for s in ["F1", "F3_C7k4", "U", "Feeders"]:
    f = f"{RB}/b3_test_{s}_{TAG}.jsonl"
    if not os.path.exists(f): continue
    fx = collections.defaultdict(lambda: collections.defaultdict(list))
    for l in open(f): x = json.loads(l); fx[(x["fmt"], x["ck"])][x["pair_id"]].append(x["p_low"])
    F = {k: pm(v) for k, v in fx.items()}; C = SEL["sets"][s]["chosen"]; src = f"results/B/b3_test_{s}_{TAG}.jsonl"
    out.append(f"\n## Fix: scale {len(C['heads'])} heads of set **{s}** (k={C['k']}, γ={C['gamma']})\n")
    out.append("| format | P_low C1 base→fix | C2k4 base→fix | C7k4 base→fix | C3k4 base→fix | C0 fix | bias red. C2k4 [CI] | bias red. C7k4 [CI] | pref. kept [CI] | corrob. kept [CI] |\n|---|---|---|---|---|---|---|---|---|---|")
    R = {}
    for fmt in ("F1", "F3", "F2"):
        if (fmt, "C1k1") not in F: continue
        P = sorted(F[(fmt, "C1k1")])
        g = lambda D, ck, ps: np.mean([D[(fmt, ck)][p] for p in ps]) if (fmt, ck) in D else np.nan
        def metric(cond):
            if (fmt, cond) not in F: return None, None
            num = lambda ps: g(F, cond, ps) - g(F, "C1k1", ps); den = lambda ps: g(B, cond, ps) - g(B, "C1k1", ps)
            v = 1 - num(P) / den(P); lo, hi = ratio_ci(num, den, P); return v, [1 - hi, 1 - lo]
        def kept(cond):
            if (fmt, cond) not in F: return None, None
            num = lambda ps: g(F, cond, ps) - g(F, "C1k1", ps); den = lambda ps: g(B, cond, ps) - g(B, "C1k1", ps)
            v = num(P) / den(P); return v, list(ratio_ci(num, den, P))
        br2, c2 = metric("C2k4"); br7, c7 = metric("C7k4"); sp, cs = kept("C0k1"); co, cc = kept("C3k4")
        R[fmt] = {"BR_C2k4": br2, "BR_C7k4": br7, "SP": sp, "CORR": co}
        fm = lambda v, c: "—" if v is None else f"{v*100:.0f}% [{c[0]*100:.0f}, {c[1]*100:.0f}]"
        bf = lambda ck: "—" if (fmt, ck) not in F else f"{g(B, ck, P):.3f}→{g(F, ck, P):.3f}"
        out.append(f"| {fmt} | {bf('C1k1')} | {bf('C2k4')} | {bf('C7k4')} | {bf('C3k4')} | {g(F, 'C0k1', P):.3f} | {fm(br2, c2)} | {fm(br7, c7)} | {fm(sp, cs)} | {fm(co, cc)} |")
        for nm, v, c in (("BR_C2k4", br2, c2), ("BR_C7k4", br7, c7), ("pref_kept", sp, cs), ("corrob_kept", co, cc)):
            if v is not None: put(f"B3.{s}.{fmt}.{nm}", v, c, len(P), src)
    cf = f"{RB}/b3_cap_{s}_{TAG}.json"
    if os.path.exists(cf):
        K = json.load(open(cf)); mb, mf = np.array(K["base"]["mmlu"]), np.array(K["fixed"]["mmlu"]); nb, nf = np.array(K["base"]["nll"]), np.array(K["fixed"]["nll"])
        d = (mf - mb) * 100; ix = rng.integers(0, len(d), (2000, len(d))); dci = np.percentile(d[ix].mean(1), [2.5, 97.5])
        pb, pf = np.exp(nb.mean()), np.exp(nf.mean()); ix2 = rng.integers(0, len(nb), (2000, len(nb)))
        pci = np.percentile((np.exp(nf[ix2].mean(1)) / np.exp(nb[ix2].mean(1)) - 1) * 100, [2.5, 97.5])
        R["cap"] = {"mmlu_base": mb.mean() * 100, "mmlu_fix": mf.mean() * 100, "mmlu_drop": -d.mean(), "ppl_base": pb, "ppl_fix": pf, "ppl_inc_pct": (pf / pb - 1) * 100}
        out.append(f"\nCapability: MMLU {mb.mean()*100:.1f} → {mf.mean()*100:.1f} (Δ {d.mean():+.1f} pts [{dci[0]:+.1f}, {dci[1]:+.1f}], n={len(d)}); "
                   f"WikiText ppl {pb:.2f} → {pf:.2f} ({(pf/pb-1)*100:+.1f}% [{pci[0]:+.1f}, {pci[1]:+.1f}], n={len(nb)})")
        rcf = os.path.relpath(cf, SPRINT)
        put(f"B3.{s}.mmlu_delta_pts", d.mean(), dci, len(d), rcf); put(f"B3.{s}.ppl_increase_pct", (pf / pb - 1) * 100, pci, len(nb), rcf)
    RES[s] = R
# verdicts
out.append("\n## Pre-registered verdicts (B3)\n")
def cap_ok(R): return "cap" in R and R["cap"]["mmlu_drop"] <= 2 and R["cap"]["ppl_inc_pct"] <= 5
def s1(R): return R.get("F1", {}).get("BR_C2k4") is not None and R["F1"]["BR_C2k4"] >= .5 and R["F1"]["SP"] >= .7 and cap_ok(R)
def s2(R): return R.get("F3", {}).get("BR_C7k4") is not None and R["F3"]["BR_C7k4"] >= .5 and R["F3"]["SP"] >= .7 and cap_ok(R)
for s, lab in (("F1", "B3-S1 (H_F1, F1)"), ("F3_C7k4", "B3-S2 (H_F3C7, F3)")):
    if s in RES:
        v = s1(RES[s]) if s == "F1" else s2(RES[s]); out.append(f"- {lab}: **{'MET' if v else 'NOT MET'}**"); put(f"B3.{lab.split()[0]}.met", float(v))
if "U" in RES:
    out.append(f"- B3-U-S1: **{'MET' if s1(RES['U']) else 'NOT MET'}**; B3-U-S2: **{'MET' if s2(RES['U']) else 'NOT MET'}**")
    put("B3-U-S1.met", float(s1(RES["U"]))); put("B3-U-S2.met", float(s2(RES["U"])))
for s, R in RES.items():
    sel_ok = {f: (R.get(f, {}).get("CORR") or 0) >= .5 for f in ("F1", "F3") if f in R}
    out.append(f"- selectivity (corroboration kept ≥ 50%) {s}: {sel_ok}")
# H-F with test curves
cv = f"{RB}/b3_curve_{TAG}.json"
if os.path.exists(cv) and "Feeders" in RES:
    CV = json.load(open(cv)); brs = RES["Feeders"]["F3"]["BR_C7k4"]; sps = RES["Feeders"]["F3"]["SP"]
    def interp(name, x):
        pts = sorted((p["BR_C7k4"], p["SP_F3"]) for p in CV["curves"][name]["points"].values())
        xs, ys = [p[0] for p in pts], [p[1] for p in pts]
        if x > max(xs): return "above", ys[int(np.argmax(xs))]
        if x < min(xs): return "below", None
        return "in", float(np.interp(x, xs, ys))
    st, yu = interp("U", brs)
    hf = (st == "in" and sps > yu) or (st == "above" and sps >= yu)
    out.append(f"- **H-F (exploratory): {'SUPPORTED' if hf else 'NOT SUPPORTED'}**: Feeders F3 BR(C7k4) {brs*100:.0f}%, pref kept {sps*100:.0f}%; U at matched BR: {st}, "
               f"{'n/a' if yu is None else f'{yu*100:.0f}%'}")
    st3, y3 = interp("F3_C7k4", brs); out.append(f"  - vs H_F3C7 at matched BR: {st3}, {'n/a' if y3 is None else f'{y3*100:.0f}%'}")
    put("B3.HF.supported", float(hf))
    import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(5.5, 4))
    for name, col in (("U", "#8a5cc2"), ("F3_C7k4", "#d1495b"), ("Feeders", "#2e9e6a")):
        pts = sorted((g_, p["BR_C7k4"], p["SP_F3"]) for g_, p in CV["curves"][name]["points"].items())
        ax.plot([p[1] for p in pts], [p[2] for p in pts], "-o", color=col, label=f"{name} (γ 0–0.75)")
        if name in RES: ax.scatter([RES[name]["F3"]["BR_C7k4"]], [RES[name]["F3"]["SP"]], s=120, facecolors="none", edgecolors=col, lw=2)
    ax.axvline(.5, color="k", ls="--", lw=.7); ax.axhline(.7, color="k", ls="--", lw=.7)
    ax.scatter([.792], [.725], marker="*", s=120, color="k", label="Schuster LoRA (Gemma-3-4B, ref.)")
    ax.set_xlabel("paraphrase repetition-bias reduction, F3 C7k4 (test)"); ax.set_ylabel("source preference kept, F3 (test)")
    ax.set_title("Qwen-7B head scaling: trade-off (circles = pre-registered chosen points)", fontsize=8); ax.legend(fontsize=7)
    fig.tight_layout(); fig.savefig(f"{FIG}/figB3_tradeoff_F3.png", dpi=180); fig.savefig(f"{FIG}/figB3_tradeoff_F3.pdf"); plt.close(fig)
# selection curves (descriptive)
out.append("\n## Selection-split γ curves (descriptive; chosen points marked *)\n")
for s, S in SEL["sets"].items():
    ch = f"k{S['chosen']['k']}_g{S['chosen']['gamma']}"
    out.append(f"- {s}: " + "; ".join(f"{kg}{'*' if kg == ch else ''} BR_F1 {d['BR_F1_C2k4']:.2f}" + (f" BR_F3C7 {d['BR_F3_C7k4']:.2f}" if 'BR_F3_C7k4' in d else "") + f" SP_F1 {d['SP_F1']:.2f}" for kg, d in S["rows"].items()))
if TAG == "Qwen2.5-7B-Instruct":
    open(f"{RB}/summary_B.md", "w").write("\n".join(out)); json.dump(NUM, open(f"{SPRINT}/numbers_B.json", "w"), indent=1)
else:
    open(f"{RB}/summary_B_{TAG}.md", "w").write("\n".join(out)); json.dump(NUM, open(f"{RB}/numbers_B_{TAG}.json", "w"), indent=1)
print("\n".join(out))
