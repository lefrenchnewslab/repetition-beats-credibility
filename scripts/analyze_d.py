"""SPRINT Block D (14 Nov 2026) - analysis of the LoRA baseline. New file.
  python3 scripts/analyze_d.py results/D  -> results/D/summary_D.md, numbers_D.json, figs/figD_tradeoff_F3.(pdf|png)
Base = Block A behaviour (same test prompts, same base model). Metrics and CIs as in analyze_b.py (pairs, 2000 bootstraps).
"""
import json, os, sys, collections
import numpy as np
RD = os.path.abspath(sys.argv[1]); S = os.path.abspath(os.path.join(RD, "..", "..")); TAG = "Qwen2.5-7B-Instruct"
rng = np.random.default_rng(0); NUM = {}; out = ["# Block D summary (auto-generated by analyze_d.py)\n"]
def put(k, v, ci=None, n=None, src=None): NUM[k] = {"value": None if v is None else float(v), "ci": None if ci is None else [float(c) for c in ci], "n": n, "source": src}
def load(f):
    D = collections.defaultdict(lambda: collections.defaultdict(list)); M = collections.defaultdict(list)
    for l in open(f):
        x = json.loads(l)
        if x.get("split", "test") != "test": continue
        D[(x["fmt"], x["ck"])][x["pair_id"]].append(x["p_low"]); M[(x["fmt"], x["ck"])].append(x["mass"])
    return {k: {p: np.mean(v) for p, v in d.items()} for k, d in D.items()}, M
B, BM = load(f"{S}/results/A/behaviour_{TAG}.jsonl")
L, LM = load(f"{RD}/b3_test_LORA_{TAG}.jsonl")
src = f"results/D/b3_test_LORA_{TAG}.jsonl"
def ratio_ci(num, den, P, n=2000):
    P = np.array(P); v = []
    for _ in range(n):
        s = P[rng.integers(0, len(P), len(P))]; d = den(s)
        if d != 0: v.append(num(s) / d)
    return np.percentile(v, [2.5, 97.5])
R = {}
out.append("| format | C1 base->LoRA | C2k4 | C7k4 | C3k4 | C0 LoRA | bias red. C2k4 [CI] | bias red. C7k4 [CI] | pref. kept [CI] | corrob. kept [CI] |\n|---|---|---|---|---|---|---|---|---|---|")
for fmt in ("F1", "F3", "F2"):
    P = sorted(L[(fmt, "C1k1")]); g = lambda D, ck, ps: np.mean([D[(fmt, ck)][p] for p in ps])
    def metric(cond, kept=False):
        if (fmt, cond) not in L: return None, None
        num = lambda ps: g(L, cond, ps) - g(L, "C1k1", ps); den = lambda ps: g(B, cond, ps) - g(B, "C1k1", ps)
        v = num(P) / den(P); lo, hi = ratio_ci(num, den, P)
        return (v, [lo, hi]) if kept else (1 - v, [1 - hi, 1 - lo])
    r = {"BR_C2k4": metric("C2k4"), "BR_C7k4": metric("C7k4"), "SP": metric("C0k1", True), "CORR": metric("C3k4", True)}; R[fmt] = r
    f = lambda t: "--" if t[0] is None else f"{t[0]*100:.0f}% [{t[1][0]*100:.0f}, {t[1][1]*100:.0f}]"
    bf = lambda ck: f"{g(B, ck, P):.3f}->{g(L, ck, P):.3f}"
    out.append(f"| {fmt} | {bf('C1k1')} | {bf('C2k4')} | {bf('C7k4')} | {bf('C3k4')} | {g(L, 'C0k1', P):.3f} | {f(r['BR_C2k4'])} | {f(r['BR_C7k4'])} | {f(r['SP'])} | {f(r['CORR'])} |")
    for nm, k in (("BR_C2k4", "BR_C2k4"), ("BR_C7k4", "BR_C7k4"), ("pref_kept", "SP"), ("corrob_kept", "CORR")):
        if r[k][0] is not None: put(f"D.{fmt}.{nm}", r[k][0], r[k][1], len(P), src)
# side effects, confidence, mass (F1 incl. held-out C6/C0r)
out.append("\n| condition (F1 unless stated) | P_low base | P_low LoRA | max-option prob base/LoRA | entropy base/LoRA (bits) | A+B mass base/LoRA |\n|---|---|---|---|---|---|")
def conf(D, k):
    x = np.array(list(D[k].values())); return np.mean(np.maximum(x, 1 - x)), np.mean(-(x * np.log2(np.clip(x, 1e-9, 1)) + (1 - x) * np.log2(np.clip(1 - x, 1e-9, 1))))
for k in [("F1", c) for c in ("C0k1", "C0rk4", "C1k1", "C2k2", "C2k4", "C2k8", "C3k4", "C5k4", "C6k2", "C6k4", "C7k4")] + [("F3", c) for c in ("C1k1", "C2k4", "C7k4", "C3k4")]:
    if k not in L or k not in B: continue
    P = sorted(L[k]); pb = np.mean([B[k][p] for p in P]); pl = np.mean([L[k][p] for p in P]); cb, cl = conf(B, k), conf(L, k)
    out.append(f"| {k[0]} {k[1]} | {pb:.3f} | {pl:.3f} | {cb[0]:.3f} / {cl[0]:.3f} | {cb[1]:.3f} / {cl[1]:.3f} | {np.mean(BM[k]):.3f} / {np.mean(LM[k]):.3f} |")
    put(f"D.{k[0]}.{k[1]}.p_low_lora", pl, n=len(P), src=src); put(f"D.{k[0]}.{k[1]}.p_low_base", pb, n=len(P), src=f"results/A/behaviour_{TAG}.jsonl")
    put(f"D.{k[0]}.{k[1]}.maxprob_lora", cl[0], src=src); put(f"D.{k[0]}.{k[1]}.entropy_lora", cl[1], src=src); put(f"D.{k[0]}.{k[1]}.mass_lora", np.mean(LM[k]), src=src)
c6 = np.mean(list(L[("F1", "C6k4")].values())) - np.mean(list(B[("F1", "C6k4")].values()))
shortcut = bool(c6 >= 0.20); put("D.shortcut.C6k4_delta", c6, src=src); put("D.shortcut.flag", float(shortcut))
# capability
K = json.load(open(f"{RD}/b3_cap_LORA_{TAG}.json")); mb, mf = np.array(K["base"]["mmlu"]), np.array(K["fixed"]["mmlu"]); nb, nf = np.array(K["base"]["nll"]), np.array(K["fixed"]["nll"])
d = (mf - mb) * 100; ix = rng.integers(0, len(d), (2000, len(d))); dci = np.percentile(d[ix].mean(1), [2.5, 97.5])
pb_, pf_ = np.exp(nb.mean()), np.exp(nf.mean()); ix2 = rng.integers(0, len(nb), (2000, len(nb))); pci = np.percentile((np.exp(nf[ix2].mean(1)) / np.exp(nb[ix2].mean(1)) - 1) * 100, [2.5, 97.5])
put("D.mmlu_delta_pts", d.mean(), dci, len(d), f"results/D/b3_cap_LORA_{TAG}.json"); put("D.ppl_increase_pct", (pf_ / pb_ - 1) * 100, pci, len(nb), f"results/D/b3_cap_LORA_{TAG}.json")
out.append(f"\nCapability: MMLU {mb.mean()*100:.1f} -> {mf.mean()*100:.1f} (delta {d.mean():+.1f} pts [{dci[0]:+.1f}, {dci[1]:+.1f}]); WikiText ppl {pb_:.2f} -> {pf_:.2f} ({(pf_/pb_-1)*100:+.1f}% [{pci[0]:+.1f}, {pci[1]:+.1f}])")
cap_ok = (-d.mean()) <= 2 and (pf_ / pb_ - 1) * 100 <= 5
S1 = R["F1"]["BR_C2k4"][0] >= .5 and R["F1"]["SP"][0] >= .7 and cap_ok; S2 = R["F3"]["BR_C7k4"][0] >= .5 and R["F3"]["SP"][0] >= .7 and cap_ok
put("D.S1.met", float(S1)); put("D.S2.met", float(S2))
# D-cmp: LoRA vs best B3 head damping at matched F3 preference
CV = json.load(open(f"{S}/results/B/b3_curve_{TAG}.json")); spL = R["F3"]["SP"][0]; brL, brci = R["F3"]["BR_C7k4"]
best = None
for name in ("U", "F3_C7k4", "Feeders"):
    pts = sorted([(p["SP_F3"], p["BR_C7k4"]) for p in CV["curves"][name]["points"].values()] + [(1.0, 0.0)])
    sps, brs = [p[0] for p in pts], [p[1] for p in pts]
    v = brs[0] if spL < sps[0] else float(np.interp(spL, sps, brs))
    if best is None or v > best[1]: best = (name, v)
verdict = "LoRA better" if brci[0] > best[1] else ("LoRA worse" if brci[1] < best[1] else "no difference")
put("D.cmp.B3_best_BR_at_matched_SP", best[1], src="results/B/b3_curve_*.json"); put("D.cmp.lora_BR", brL, brci); put("D.cmp.lora_better", float(verdict == "LoRA better"))
out.append("\n## Pre-registered verdicts\n")
out.append(f"- D-S1 (F1 exact copies): **{'MET' if S1 else 'NOT MET'}** (bias red. {R['F1']['BR_C2k4'][0]*100:.0f}%, pref kept {R['F1']['SP'][0]*100:.0f}%, MMLU {d.mean():+.1f}, ppl {(pf_/pb_-1)*100:+.1f}%)")
out.append(f"- D-S2 (F3 paraphrases): **{'MET' if S2 else 'NOT MET'}** (bias red. {brL*100:.0f}%, F3 pref kept {spL*100:.0f}%)")
out.append(f"- D-sel: corroboration kept F1 {R['F1']['CORR'][0]*100:.0f}%, F3 {R['F3']['CORR'][0]*100:.0f}%, F2 {R['F2']['CORR'][0]*100:.0f}% (selective if >= 50%)")
out.append(f"- D-cmp (F3/C7 at matched preference {spL*100:.0f}%): LoRA {brL*100:.0f}% [{brci[0]*100:.0f}, {brci[1]*100:.0f}] vs best B3 head damping {best[1]*100:.0f}% ({best[0]}) -> **{verdict}**")
out.append(f"- D-shortcut (exploratory): C6 k=4 P_low change {c6:+.3f} -> {'FLAG: minority shortcut' if shortcut else 'no flag'}")
open(f"{RD}/summary_D.md", "w").write("\n".join(out)); json.dump(NUM, open(f"{S}/numbers_D.json", "w"), indent=1); print("\n".join(out))
# figure: B3 curves + LoRA point + Schuster point
import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False, "pdf.fonttype": 42})
fig, ax = plt.subplots(figsize=(5.2, 3.4))
for name, lab, col in (("U", "head damping: union", "#8a5cc2"), ("F3_C7k4", "head damping: paraphrase heads", "#d1495b"), ("Feeders", "head damping: feeder heads", "#2e9e6a")):
    pts = sorted((float(g_), p["BR_C7k4"], p["SP_F3"]) for g_, p in CV["curves"][name]["points"].items())
    ax.plot([p[1] * 100 for p in pts], [p[2] * 100 for p in pts], "-o", ms=3.5, lw=1.3, color=col, label=lab)
ax.errorbar([brL * 100], [spL * 100], xerr=[[brL * 100 - brci[0] * 100], [brci[1] * 100 - brL * 100]], yerr=[[spL * 100 - R["F3"]["SP"][1][0] * 100], [R["F3"]["SP"][1][1] * 100 - spL * 100]],
            fmt="D", ms=7, color="#e8a33d", ecolor="#e8a33d", capsize=3, label="trained LoRA, same model (Qwen-7B)")
ax.scatter([79.2], [72.5], marker="*", s=110, color="k", label="trained LoRA, Schuster et al. (different model)")
ax.axvline(50, color="k", ls="--", lw=.7); ax.axhline(70, color="k", ls="--", lw=.7); ax.fill_between([50, 100], 70, 115, color="#2e9e6a", alpha=.07)
ax.annotate(f"independent users: {R['F3']['CORR'][0]*100:.0f}% kept", (brL * 100, spL * 100), xytext=(-8, 8), textcoords="offset points", ha="right", fontsize=7.5, color="#b07415")
_bp = NUMB = json.load(open(f"{S}/numbers_B.json"))
_x, _y, _c = NUMB["B3.F3_C7k4.F3.BR_C7k4"]["value"], NUMB["B3.F3_C7k4.F3.pref_kept"]["value"], NUMB["B3.F3_C7k4.F3.corrob_kept"]["value"]
ax.annotate(f"independent users: {_c*100:.0f}% kept", (_x * 100, _y * 100), xytext=(8, 4), textcoords="offset points", fontsize=7.5, color="#d1495b")
ax.set_xlim(0, 100); ax.set_ylim(0, 115); ax.set_xlabel("paraphrase bias removed (%), documents, test"); ax.set_ylabel("source preference kept (%)")
ax.legend(fontsize=7.5, frameon=False, loc="lower left"); fig.tight_layout()
